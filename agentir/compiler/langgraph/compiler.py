"""LangGraph Workflow Compiler.

Compiles AgentIR WorkflowDefinitions into LangGraph Python code.

LangGraph uses a StateGraph with nodes and edges:
    - Each agent/tool becomes a node function
    - Sequence → serial edges
    - Parallel → parallel node execution (subgraphs)
    - Condition → conditional_edges
    - Loop → conditional_edges with counter
    - SubWorkflow → compiled as subgraph

The generated code produces a compilable ``app = graph.compile()`` that
can be run with ``app.invoke(initial_state)``.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Literal

from agentir.compiler.base import BaseCompiler, CompilationResult
from agentir.ir.models import WorkflowDefinition
from agentir.ir.nodes import (
    AgentNode,
    ConditionNode,
    LoopNode,
    ParallelNode,
    SequenceNode,
    SubWorkflowNode,
    ToolNode,
    WorkflowNode,
)
from agentir.llm.config import AgentConfig


# ---- IR Tree Walkers ----

def _collect_agents(node: WorkflowNode) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []

    def _walk(n: WorkflowNode) -> None:
        if isinstance(n, AgentNode):
            if n.agent not in seen:
                seen.add(n.agent)
                result.append(n.agent)
        elif isinstance(n, SequenceNode):
            for step in n.steps:
                _walk(step)
        elif isinstance(n, ParallelNode):
            for branch in n.branches:
                _walk(branch)
        elif isinstance(n, ConditionNode):
            _walk(n.true_branch)
            _walk(n.false_branch)
        elif isinstance(n, LoopNode):
            _walk(n.body)
        elif isinstance(n, (ToolNode, SubWorkflowNode)):
            pass

    _walk(node)
    return result


def _collect_agent_instructions(node: WorkflowNode) -> dict[str, str]:
    """Collect per-node instructions for each agent."""
    instructions: dict[str, str] = {}

    def _walk(n: WorkflowNode) -> None:
        if isinstance(n, AgentNode):
            if n.agent not in instructions and n.instruction:
                instructions[n.agent] = n.instruction
        elif isinstance(n, SequenceNode):
            for step in n.steps:
                _walk(step)
        elif isinstance(n, ParallelNode):
            for branch in n.branches:
                _walk(branch)
        elif isinstance(n, ConditionNode):
            _walk(n.true_branch)
            _walk(n.false_branch)
        elif isinstance(n, LoopNode):
            _walk(n.body)

    _walk(node)
    return instructions


def _collect_tools(node: WorkflowNode) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []

    def _walk(n: WorkflowNode) -> None:
        if isinstance(n, ToolNode):
            if n.tool not in seen:
                seen.add(n.tool)
                result.append(n.tool)
        elif isinstance(n, SequenceNode):
            for step in n.steps:
                _walk(step)
        elif isinstance(n, ParallelNode):
            for branch in n.branches:
                _walk(branch)
        elif isinstance(n, ConditionNode):
            _walk(n.true_branch)
            _walk(n.false_branch)
        elif isinstance(n, LoopNode):
            _walk(n.body)
        elif isinstance(n, (AgentNode, SubWorkflowNode)):
            pass

    _walk(node)
    return result


# ---- Code Generator ----

def _generate_langgraph_code(
    workflow: WorkflowDefinition,
    agent_configs: dict[str, AgentConfig] | None = None,
    subworkflow_resolver: Callable[[str], WorkflowDefinition | None] | None = None,
) -> str:
    """Generate LangGraph Python source code from a workflow definition."""
    agent_configs = agent_configs or {}
    lines: list[str] = []
    sep = "# " + "=" * 60

    # Header
    lines.append("# Generated by AgentIR LangGraph Compiler v0.1.0")
    lines.append("# Target: LangGraph (https://langchain-ai.github.io/langgraph/)")
    lines.append("")
    lines.append("from langgraph.graph import StateGraph, END, START")
    lines.append("from typing import TypedDict, Annotated")
    lines.append("import operator")
    lines.append("")
    lines.append("")
    lines.append(sep)
    lines.append("# Workflow State")
    lines.append(sep)
    lines.append("")
    lines.append("class WorkflowState(TypedDict):")
    lines.append('    messages: Annotated[list, operator.add]')
    lines.append("    output: str")
    lines.append("    loop_count: int")
    lines.append("    condition_result: str")
    lines.append("")
    lines.append("")

    # Agent definitions
    agent_names = _collect_agents(workflow.root)
    agent_instructions = _collect_agent_instructions(workflow.root)
    tool_names = _collect_tools(workflow.root)

    lines.append(sep)
    lines.append("# Agent Definitions (user-provided implementations)")
    lines.append(sep)
    lines.append("")

    for agent_name in agent_names:
        cfg = agent_configs.get(agent_name)
        instruction = (
            agent_instructions.get(agent_name)
            or (cfg.instruction if cfg else "")
            or f"Agent: {agent_name}"
        )
        model = cfg.model if cfg else "gpt-4o"
        lines.append(f"# Agent: {agent_name}")
        lines.append(f"# Model: {model}")
        lines.append(f'# Instruction: "{instruction}"')
        lines.append(f"def {agent_name}_node(state: WorkflowState) -> dict:")
        lines.append(f'    """Agent node: {agent_name}"""')
        lines.append(f"    # TODO: Implement agent logic using your preferred LLM")
        lines.append(f'    output = state.get("output", "")')
        lines.append(f'    return {{"output": output, "messages": []}}')
        lines.append("")

    # Tool definitions
    if tool_names:
        lines.append(sep)
        lines.append("# Tool Node Definitions")
        lines.append(sep)
        lines.append("")
        for tool_name in tool_names:
            lines.append(f"# Tool: {tool_name}")
            lines.append(f"def {tool_name}_node(state: WorkflowState) -> dict:")
            lines.append(f'    """Tool node: {tool_name}"""')
            lines.append(f"    # TODO: Implement tool logic")
            lines.append(f'    output = state.get("output", "")')
            lines.append(f'    return {{"output": output}}')
            lines.append("")

    # Build graph
    lines.append(sep)
    lines.append("# Graph Construction")
    lines.append(sep)
    lines.append("")
    lines.append("graph = StateGraph(WorkflowState)")
    lines.append("")

    # Register nodes
    for agent_name in agent_names:
        lines.append(f'graph.add_node("{agent_name}", {agent_name}_node)')
    for tool_name in tool_names:
        lines.append(f'graph.add_node("{tool_name}", {tool_name}_node)')
    lines.append("")

    # Generate edges from the IR tree
    edge_lines, _ = _generate_edges(workflow.root, agent_names, tool_names)
    lines.extend(edge_lines)

    # Compile
    lines.append("")
    lines.append(sep)
    lines.append("# Compiled Application")
    lines.append(sep)
    lines.append("")
    lines.append("app = graph.compile()")
    lines.append("")
    lines.append("# Usage:")
    lines.append("# result = app.invoke({")
    lines.append('#     "messages": [HumanMessage(content="your input")],')
    lines.append('#     "output": "",')
    lines.append('#     "loop_count": 0,')
    lines.append('#     "condition_result": "",')
    lines.append("# })")
    lines.append("")

    return "\n".join(lines)


def _node_func_name(node: WorkflowNode) -> str:
    """Get the function name for a node."""
    if isinstance(node, AgentNode):
        return node.agent
    if isinstance(node, ToolNode):
        return node.tool
    if isinstance(node, SubWorkflowNode):
        return f"sub_{node.workflow}"
    return "unknown"


def _generate_edges(
    node: WorkflowNode,
    agent_names: list[str],
    tool_names: list[str],
    entry_id: str = "START",
    counter: list[int] | None = None,
) -> tuple[list[str], str]:
    """Recursively generate LangGraph edges. Returns (lines, exit_node_id)."""
    if counter is None:
        counter = [0]
    lines: list[str] = []

    if isinstance(node, AgentNode) or isinstance(node, ToolNode):
        name = _node_func_name(node)
        lines.append(f'graph.add_edge("{entry_id}", "{name}")')
        return lines, name

    elif isinstance(node, SubWorkflowNode):
        name = f"sub_{node.workflow}"
        # Register subworkflow node
        lines.append(f'graph.add_node("{name}", lambda s: s)  # SubWorkflow placeholder')
        lines.append(f'graph.add_edge("{entry_id}", "{name}")')
        return lines, name

    elif isinstance(node, SequenceNode):
        current = entry_id
        last_exit = current
        for step in node.steps:
            step_lines, exit_id = _generate_edges(step, agent_names, tool_names, current, counter)
            lines.extend(step_lines)
            current = exit_id
            last_exit = exit_id
        return lines, last_exit

    elif isinstance(node, ParallelNode):
        # LangGraph doesn't have native parallel - use a fork/join pattern
        fork_id = f"__fork_{counter[0]}"
        counter[0] += 1
        join_id = f"__join_{counter[0]}"
        counter[0] += 1

        lines.append(f'graph.add_node("{fork_id}", lambda s: s)  # Fork')
        lines.append(f'graph.add_node("{join_id}", lambda s: s)  # Join')
        lines.append(f'graph.add_edge("{entry_id}", "{fork_id}")')

        for branch in node.branches:
            branch_lines, branch_exit = _generate_edges(
                branch, agent_names, tool_names, fork_id, counter
            )
            lines.extend(branch_lines)
            lines.append(f'graph.add_edge("{branch_exit}", "{join_id}")')

        return lines, join_id

    elif isinstance(node, ConditionNode):
        cond_id = f"__cond_{counter[0]}"
        counter[0] += 1

        lines.append(f'# Condition: {node.expression}')
        lines.append(f'graph.add_edge("{entry_id}", "{cond_id}")')

        # Generate true branch
        true_lines, true_exit = _generate_edges(
            node.true_branch, agent_names, tool_names, cond_id, counter
        )
        lines.extend(true_lines)

        # Generate false branch
        false_lines, false_exit = _generate_edges(
            node.false_branch, agent_names, tool_names, cond_id, counter
        )
        lines.extend(false_lines)

        # Add conditional routing
        merge_id = f"__merge_{counter[0]}"
        counter[0] += 1
        lines.append(f'graph.add_node("{merge_id}", lambda s: s)  # Merge')
        lines.append(f'graph.add_edge("{true_exit}", "{merge_id}")')
        lines.append(f'graph.add_edge("{false_exit}", "{merge_id}")')

        # Register the condition function
        lines.append("")
        lines.append(f"def route_{cond_id}(state: WorkflowState) -> str:")
        lines.append(f'    """Route based on: {node.expression}"""')
        lines.append(f'    result = state.get("condition_result", "")')
        lines.append(f'    if result == "true":')
        lines.append(f'        return "{true_exit}"')
        lines.append(f'    return "{false_exit}"')
        lines.append("")
        lines.append(f'graph.add_conditional_edges("{cond_id}", route_{cond_id}, {{')
        lines.append(f'    "{true_exit}": "{true_exit}",')
        lines.append(f'    "{false_exit}": "{false_exit}",')
        lines.append("})")

        return lines, merge_id

    elif isinstance(node, LoopNode):
        loop_id = f"__loop_{counter[0]}"
        counter[0] += 1
        exit_id = f"__loop_exit_{counter[0]}"
        counter[0] += 1

        max_it = node.max_iterations

        lines.append(f'# Loop (max {max_it} iterations)')
        lines.append(f'graph.add_edge("{entry_id}", "{loop_id}")')

        # Generate body
        body_lines, body_exit = _generate_edges(
            node.body, agent_names, tool_names, loop_id, counter
        )
        lines.extend(body_lines)

        # Loop routing function
        lines.append("")
        lines.append(f"def route_{loop_id}(state: WorkflowState) -> str:")
        lines.append(f'    """Loop router (max {max_it})"""')
        lines.append(f"    count = state.get(\"loop_count\", 0) + 1")
        lines.append(f"    if count >= {max_it}:")
        lines.append(f'        return "{exit_id}"')
        lines.append(f'    return "{loop_id}"')
        lines.append("")

        lines.append(f'graph.add_conditional_edges("{body_exit}", route_{loop_id}, {{')
        lines.append(f'    "{loop_id}": "{loop_id}",')
        lines.append(f'    "{exit_id}": "{exit_id}",')
        lines.append("})")

        return lines, exit_id

    return lines, entry_id


# ---- LangGraph Compiler ----

@dataclass
class LangGraphCompiler(BaseCompiler):
    """Compiles AgentIR workflows to LangGraph Python code.

    Usage:
        result = LangGraphCompiler().compile(workflow)
        print(result.source_code)
    """

    runtime: str = "langgraph"

    def compile(
        self,
        workflow: WorkflowDefinition,
        agent_configs: dict[str, AgentConfig] | None = None,
        subworkflow_resolver: Callable[[str], WorkflowDefinition | None] | None = None,
        **kwargs: object,
    ) -> CompilationResult:
        """Compile a WorkflowDefinition to LangGraph Python source.

        Args:
            workflow: The validated AgentIR workflow.
            agent_configs: Optional per-agent configuration.
            subworkflow_resolver: Optional callback to resolve sub-workflows.
            **kwargs: Reserved for future options.

        Returns:
            CompilationResult with the generated Python source code.
        """
        try:
            source_code = _generate_langgraph_code(
                workflow,
                agent_configs=agent_configs,
                subworkflow_resolver=subworkflow_resolver,
            )

            return CompilationResult(
                success=True,
                source_code=source_code,
                runtime=self.runtime,
            )
        except Exception as e:
            return CompilationResult(
                success=False,
                errors=[str(e)],
                runtime=self.runtime,
            )
